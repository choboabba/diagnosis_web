def generate_action_plan(answers: List[Any], parent_type: str) -> Dict[str, Any]:
    """
    30문항 답변 + parent_type 기반 맞춤 실행 플랜 반환.

    answers 인덱스 (0-based):
      answers[21] = Q22 끊기는 지점  (int 1~5)
      answers[23] = Q24 변화 욕구    (int 1~5)
      answers[26] = Q27 붕괴 원인    (int 1~5)
    """
    def _safe(val: Any, lo: int = 1, hi: int = 5, default: int = 3) -> int:
        try:
            v = int(val)
            return v if lo <= v <= hi else default
        except (TypeError, ValueError):
            return default

    break_point_idx = _safe(answers[21])
    change_goal_idx = _safe(answers[23])
    collapse_cause_idx = _safe(answers[26])

    bp = BREAK_POINT_STRATEGIES.get(break_point_idx, BREAK_POINT_STRATEGIES[3])
    fs = FIRST_STEPS.get(change_goal_idx, FIRST_STEPS[3])

    roadmap = ROADMAPS.get(parent_type, ROADMAPS[_FALLBACK_TYPE])
    checklist = CHECKLISTS.get(parent_type, CHECKLISTS[_FALLBACK_TYPE])

    week1_base = WEEK1_FOCUS_BASE.get(parent_type, WEEK1_FOCUS_BASE[_FALLBACK_TYPE])
    week1_addendum = BREAK_POINT_ADDENDUM.get(break_point_idx, BREAK_POINT_ADDENDUM[3])
    week1_focus = f"{week1_base} {week1_addendum}"

    collapse_cause_labels = {
        1: "체력 부족",
        2: "감정 누적",
        3: "기준 혼란",
        4: "실행 실패",
        5: "외부 영향",
    }
    collapse_cause_text = collapse_cause_labels.get(collapse_cause_idx, "복합 원인")

    return {
        "week1_focus": week1_focus,
        "roadmap": roadmap,
        "break_point_label": bp["label"],
        "break_point_insight": bp["insight"],
        "break_point_strategy": bp["strategy"],
        "collapse_cause": collapse_cause_text,
        "first_step_label": fs["label"],
        "first_step_today": fs["action"],
        "first_step_why": fs["why"],
        "checklist": checklist,
    }
